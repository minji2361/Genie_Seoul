-- =============================================================================
-- Genie / Reframe — Interview 와 Dashboard 테이블 완전 분리 스키마
-- =============================================================================
-- 설계 원칙
--   * Interview 화면(/interview)         → int_interviews 테이블만 사용 (단독)
--   * Dashboard 화면(/dashboard)         → participant + 검사 테이블들 (단독)
--   * 두 영역이 "공통"으로 쓰는 것은 딱 둘:
--       1) 인증        : auth.users  +  public.counselors
--       2) 서명 저장소 : storage 'signatures' 버킷
--   * 그 외에는 서로 참조하지 않으므로 각자 독립적으로 저장/조회/삭제됩니다.
--
-- 사용법: Supabase 대시보드 → SQL Editor 에 전체를 붙여넣고 실행.
--         여러 번 실행해도 안전(idempotent)합니다.
-- =============================================================================

create extension if not exists "pgcrypto";


-- =============================================================================
-- [공통 1] 인증 — counselors (auth.users 와 1:1)
-- =============================================================================
create table if not exists public.counselors (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null unique references auth.users (id) on delete cascade,
    name text not null,
    email text not null,
    region text not null,
    photo_url text
);

-- 로그인 시 본인 counselor 행을 조회/생성하므로, 본인 행만 접근 허용
alter table public.counselors enable row level security;

drop policy if exists "counselors_select_self" on public.counselors;
create policy "counselors_select_self" on public.counselors
  for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists "counselors_insert_self" on public.counselors;
create policy "counselors_insert_self" on public.counselors
  for insert to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "counselors_update_self" on public.counselors;
create policy "counselors_update_self" on public.counselors
  for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);


-- =============================================================================
-- [공통 2] 서명 저장소 — storage 'signatures' 버킷
--   participant.signatureurl / int_interviews.signatureurl 둘 다 이 버킷을 가리킴
-- =============================================================================
insert into storage.buckets (id, name, public)
values ('signatures', 'signatures', true)
on conflict (id) do nothing;

drop policy if exists "signatures_public_read" on storage.objects;
create policy "signatures_public_read"
  on storage.objects for select to public
  using (bucket_id = 'signatures');

drop policy if exists "signatures_authenticated_insert" on storage.objects;
create policy "signatures_authenticated_insert"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'signatures');

drop policy if exists "signatures_authenticated_update" on storage.objects;
create policy "signatures_authenticated_update"
  on storage.objects for update to authenticated
  using (bucket_id = 'signatures')
  with check (bucket_id = 'signatures');


-- =============================================================================
-- [DASHBOARD] 코칭 대상자 — participant (단독)
-- =============================================================================
create table if not exists public.participant (
    id uuid primary key default gen_random_uuid(),
    name text not null,
    birth_date text not null,
    stress text not null,
    religion text not null,
    signatureurl text not null,
    counselors uuid not null references auth.users (id) on delete cascade,
    created_at timestamptz not null default now()
);

-- 실수로 컬럼이 삭제/변경된 경우를 대비한 보정
alter table public.participant add column if not exists name text;
alter table public.participant add column if not exists birth_date text;
alter table public.participant add column if not exists stress text;
alter table public.participant add column if not exists religion text;
alter table public.participant add column if not exists signatureurl text;
alter table public.participant add column if not exists counselors uuid;
alter table public.participant add column if not exists created_at timestamptz not null default now();

create index if not exists idx_participant_counselors on public.participant (counselors);

alter table public.participant enable row level security;

drop policy if exists "participant_counselor_all" on public.participant;
create policy "participant_counselor_all" on public.participant
  for all to authenticated
  using (auth.uid() = counselors)
  with check (auth.uid() = counselors);


-- =============================================================================
-- [DASHBOARD] 검사 테이블들 — participant 에만 종속 (참가자 삭제 시 함께 삭제)
