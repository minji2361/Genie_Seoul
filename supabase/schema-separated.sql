);

create table if not exists public.sixtypes (
    id bigint generated by default as identity primary key,
    participant_id uuid not null references public.participant (id) on delete cascade,
    image_url text not null
);

create table if not exists public.fourtypes (
    id bigint generated by default as identity primary key,
    participant_id uuid not null references public.participant (id) on delete cascade,
    image_url text not null
);

-- 검사 테이블 RLS: 해당 participant 를 소유한 상담사만 접근
do $$
declare
    t text;
begin
    foreach t in array array[
        'core_emotion_tests','personality_tests','personality_tests2',
        'attachment_tests','lifegraphs','sixtypes','fourtypes'
    ] loop
        execute format('alter table public.%I enable row level security;', t);
        execute format('drop policy if exists %I on public.%I;', t || '_by_owner', t);
        execute format($f$
            create policy %I on public.%I
              for all to authenticated
              using (exists (
                  select 1 from public.participant p
                  where p.id = %I.participant_id and p.counselors = auth.uid()
              ))
              with check (exists (
                  select 1 from public.participant p
                  where p.id = %I.participant_id and p.counselors = auth.uid()
              ));
        $f$, t || '_by_owner', t, t, t);
    end loop;
end $$;

-- 이미지 검사용 스토리지 버킷 (dashboard 전용)
insert into storage.buckets (id, name, public)
values
    ('lifegraph', 'lifegraph', true),
    ('sixtypes', 'sixtypes', true),
    ('fourtypes', 'fourtypes', true)
on conflict (id) do nothing;

do $$
declare
    b text;
begin
    foreach b in array array['lifegraph','sixtypes','fourtypes'] loop
        execute format('drop policy if exists %I on storage.objects;', b || '_public_read');
        execute format($f$
            create policy %I on storage.objects for select to public
            using (bucket_id = %L);
        $f$, b || '_public_read', b);

        execute format('drop policy if exists %I on storage.objects;', b || '_auth_insert');
        execute format($f$
            create policy %I on storage.objects for insert to authenticated
            with check (bucket_id = %L);
        $f$, b || '_auth_insert', b);
    end loop;
end $$;


-- =============================================================================
-- [INTERVIEW] 지니 인터뷰 — int_interviews (단독)
--   participant 를 전혀 참조하지 않음. auth 와 signatures 버킷만 공유.
